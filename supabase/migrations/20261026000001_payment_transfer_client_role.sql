-- =====================================================================
-- Новые значения enum — отдельной миграцией: значение, добавленное через
-- ALTER TYPE … ADD VALUE, нельзя использовать в той же транзакции.
-- Используются в 20261026000002.
-- =====================================================================

-- §7.2 «Перевод (MBank, Optima и др.) — отмечается вручную». В движке были
-- только наличные и терминал, и перевод записывать было некуда, хотя в
-- отчётах Академии это больше половины оплат.
alter type payment_method add value if not exists 'transfer';

-- История оплат из Excel (август 2025 – февраль 2026): способ оплаты там не
-- записывался. Ставить таким строкам «наличные» значило бы исказить кассу,
-- поэтому — честное «не указан». В формах продажи его нет.
alter type payment_method add value if not exists 'unknown';

-- Взрослый клиент, который сам заходит в приложение (просьба Академии
-- 2026-10-26): держатель входа и ученик — один человек. Права те же, что у
-- родителя (через families.parent_user_id), отличается только подача.
alter type user_role add value if not exists 'client';
