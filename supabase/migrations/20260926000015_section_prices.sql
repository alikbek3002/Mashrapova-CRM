-- =====================================================================
-- Цены в карточке секции — ТЗ §5.1 и §4.1.
--
-- §5.1 перечисляет в карточке секции «Стоимость абонемента и пробной
-- тренировки». §4.1 в таблице тарифов ставит разовому занятию и пробной
-- тренировке цену «По секции» — то есть ТЗ задаёт не только цифры, но и
-- сам механизм: у шести дисциплин цены могут различаться.
--
-- Почему этих полей не было
-- -------------------------
-- Колонки sections.subscription_price и trial_price существовали в
-- движке Uniqum и были удалены миграцией 20260807000001: прежний клиент
-- решил, что цена живёт на абонементе, а секция остаётся справочником
-- направления. Для Академии Машрапова это не так.
--
-- Как сделано
-- -----------
-- Не возвращаем прежнюю схему «цена только на секции» и не дублируем
-- каталог тарифов. Секция получает ПЕРЕОПРЕДЕЛЕНИЯ: если цена задана —
-- она главнее каталога, если нет — берётся цена тарифа как раньше.
-- Так клубные тарифы §4.1 (детский 2 500, взрослый 2 800, пакеты)
-- остаются едиными, а разовое и пробное могут различаться по дисциплинам.
--
-- Пустое поле означает «берём из каталога», и это не заглушка, а рабочее
-- состояние: пока Академия не назовёт цены по каждой из шести дисциплин,
-- всё считается как сегодня. Предзаполнять секции текущими 500 сом
-- намеренно не стали — получилось бы семь копий одной цифры, которые
-- пришлось бы держать в синхроне руками.
-- =====================================================================

alter table sections
  -- §4.1: «Пробная тренировка — по секции».
  add column if not exists trial_price numeric(12, 2),
  -- §4.1: «Разовое занятие — по секции».
  add column if not exists single_price numeric(12, 2),
  -- §5.1: «Стоимость абонемента». Ориентир для дисциплины; при продаже
  -- по тарифу из каталога главнее тариф — иначе клубные цены §4.1
  -- (детский 2 500, взрослый 2 800) пришлось бы дублировать в каждой
  -- секции и держать в синхроне руками.
  add column if not exists subscription_price numeric(12, 2);

alter table sections drop constraint if exists sections_prices_non_negative;
alter table sections add constraint sections_prices_non_negative check (
  (trial_price is null or trial_price >= 0)
  and (single_price is null or single_price >= 0)
  and (subscription_price is null or subscription_price >= 0)
);

comment on column sections.trial_price is
  'ТЗ §4.1 и §5.1: цена пробной тренировки для этой секции. NULL — берём цену тарифа «Пробная тренировка» из каталога.';
comment on column sections.single_price is
  'ТЗ §4.1: цена разового занятия для этой секции. NULL — берём цену тарифа «Разовое занятие» из каталога.';
comment on column sections.subscription_price is
  'ТЗ §5.1: ориентировочная стоимость абонемента для этой секции. При продаже по тарифу из каталога главнее тариф.';

-- ---------------------------------------------------------------------
-- section_price() — цена для секции с откатом на каталог
--
-- Одна точка правды для бэкенда, формы продажи и отчётов: иначе «что
-- главнее, секция или тариф» решалось бы в каждом месте заново.
-- ---------------------------------------------------------------------
create or replace function section_price(p_section uuid, p_type card_type)
returns numeric
language sql
stable
as $section_price$
  select coalesce(
    case p_type
      when 'trial'  then s.trial_price
      when 'single' then s.single_price
      else s.subscription_price
    end,
    -- Откат на клубный каталог: цена тарифа того же типа.
    (select p.price from card_plans p
      where p.organization_id = s.organization_id
        and p.type = p_type
        and p.is_active
      order by p.sort_order
      limit 1)
  )
  from sections s
  where s.id = p_section;
$section_price$;

comment on function section_price(uuid, card_type) is
  'ТЗ §4.1 и §5.1: цена для секции по типу абонемента. Цена секции главнее; если не задана — цена тарифа из каталога.';

