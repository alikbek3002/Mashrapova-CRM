-- =====================================================================
-- Чистка orphan-уроков.
--
-- Контекст: при изменениях расписания группы (например, было «09:00 и
-- 10:00 Пн/Ср/Пт», стало «09:00 Пн/Ср/Пт») старые lessons на 10:00
-- остались в БД, хотя в group_schedule их уже нет. На фронте это ломало
-- календарь родителя/ростер тренера: cap «6 занятий по абонементу»
-- съедался дубликатами за один день вместо реальных будущих дат.
--
-- Правило: урок «orphan», если для него нет совпадающей строки в
-- group_schedule по (group_id, day_of_week, start_time). Если на таком
-- уроке нет ни одной отметки посещения — он не несёт исторической
-- ценности и может быть удалён.
-- =====================================================================

delete from lessons l
where not exists (
  select 1 from group_schedule gs
  where gs.group_id   = l.group_id
    and gs.day_of_week = extract(dow from l.date)::int
    and gs.start_time  = l.start_time
)
and not exists (
  select 1 from attendance a where a.lesson_id = l.id
);
