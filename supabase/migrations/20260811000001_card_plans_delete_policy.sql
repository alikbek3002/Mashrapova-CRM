-- =====================================================================
-- Каталог видов абонементов ведёт клуб сам (страница «Абонементы» →
-- «Виды абонементов»). Директору нужно уметь удалять ошибочно созданный
-- вид. До сих пор delete-политики не было: supabase.delete() молча
-- удалял 0 строк.
--
-- Удаление разрешаем только директору. Проданные карты защищает FK
-- club_cards.plan_id → card_plans.id (ON DELETE NO ACTION): попытка
-- удалить использованный вид падает с 23503, фронт показывает
-- «выключите вместо удаления».
-- =====================================================================

drop policy if exists card_plans_director_delete on card_plans;
create policy card_plans_director_delete on card_plans for delete
  using (is_director() and organization_id = auth_org());
