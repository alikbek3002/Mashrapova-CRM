-- =====================================================================
-- Двухфакторная аутентификация становится настройкой клуба.
--
-- ТЗ §12.3 требует второй фактор директору и управляющему, и
-- 20260926000010 зашил это в триггер: mfa_required выводился из роли и
-- поменять его было нельзя — любое изменение роли возвращало требование
-- обратно.
--
-- Решение владельца: пока отключить. Причина практическая — клуб только
-- запускается, учётная запись директора одна, и экран обязательной
-- настройки аутентификатора стоит поперёк первого входа.
--
-- Поэтому требование не выпиливается, а выносится в настройки. Разница
-- существенная: выпиленное требование пришлось бы возвращать миграцией
-- и вспоминать, что именно было в §12.3, а настройка включается
-- галочкой, и текст ТЗ остаётся описанием значения по умолчанию.
--
-- Что НЕ меняется
-- ---------------
-- Проверка mfa_satisfied() и RESTRICTIVE-политики на денежных таблицах
-- остаются как были. Они работают по факту: есть подтверждённый фактор —
-- требуем aal2, нет фактора — пропускаем. То есть сотрудник, который
-- подключил аутентификатор добровольно, по-прежнему обязан им
-- пользоваться, даже когда требование для его роли выключено.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Роли, которым второй фактор обязателен
--
-- Массив ролей, а не булев флаг: §12.3 называет двух, и клуб может
-- захотеть оставить требование управляющему, сняв с директора, или
-- наоборот распространить на старшего менеджера. Пустой массив —
-- выключено для всех.
-- ---------------------------------------------------------------------
alter table org_settings
  add column if not exists mfa_required_roles user_role[]
    not null default array['director', 'fitness_director']::user_role[];

comment on column org_settings.mfa_required_roles is
  'ТЗ §12.3: роли, которым обязателен второй фактор. По умолчанию директор и управляющий. Пустой массив — требование выключено для всех; уже подключённый аутентификатор при этом продолжает действовать.';

-- Решение владельца на момент запуска: требование снято.
update org_settings set mfa_required_roles = '{}'::user_role[];

-- ---------------------------------------------------------------------
-- Триггер читает настройку вместо жёсткого списка
-- ---------------------------------------------------------------------
create or replace function fn_sync_mfa_required() returns trigger
language plpgsql
security definer
set search_path = public
as $sync_mfa$
declare
  v_roles user_role[];
begin
  select s.mfa_required_roles into v_roles
    from org_settings s
   where s.organization_id = new.organization_id;

  -- Нет строки настроек — держимся буквы ТЗ §12.3. Это не должно
  -- случаться (настройки ставит триггер на создании организации), но
  -- молча снимать требование безопасности из-за отсутствующей строки
  -- нельзя.
  if v_roles is null then
    v_roles := array['director', 'fitness_director']::user_role[];
  end if;

  new.mfa_required := new.role = any (v_roles);
  return new;
end;
$sync_mfa$;

comment on function fn_sync_mfa_required() is
  'ТЗ §12.3: требование второго фактора следует за ролью и настройкой org_settings.mfa_required_roles.';

-- Триггер срабатывает только при изменении роли, поэтому смена самой
-- настройки сама по себе ничего не пересчитает. Приводим в соответствие.
update profiles p
   set mfa_required = p.role = any (
         coalesce(
           (select s.mfa_required_roles from org_settings s
             where s.organization_id = p.organization_id),
           array['director', 'fitness_director']::user_role[]
         )
       )
 where p.mfa_required is distinct from p.role = any (
         coalesce(
           (select s.mfa_required_roles from org_settings s
             where s.organization_id = p.organization_id),
           array['director', 'fitness_director']::user_role[]
         )
       );

notify pgrst, 'reload schema';
